// Writes src/html/encoding-tables.ts and src/html/encoding-labels.ts from the
// WHATWG Encoding Standard's own data: its indexes, which are the only source
// a legacy encoding is exact in (ICU's `euc-kr` has no UHC and its `big5` no
// HKSCS), and its labels.
//
//   curl -O https://encoding.spec.whatwg.org/indexes.json
//   curl -O https://encoding.spec.whatwg.org/encodings.json
//   node scripts/encoding-tables.mjs indexes.json encodings.json
//   npx prettier --write src/html/encoding-tables.ts src/html/encoding-labels.ts
//
// An index is a string of its code points, one a pointer, and a run of
// pointers with none is U+FFFF and the run's length (`indexOf` in
// src/html/encoding-codecs.ts expands it). No index holds U+FFFF.
import { readFileSync, writeFileSync } from 'node:fs';

const [indexesFile, encodingsFile] = process.argv.slice(2);
if (!indexesFile || !encodingsFile) {
  console.error('usage: encoding-tables.mjs <indexes.json> <encodings.json>');
  process.exit(2);
}
const indexes = JSON.parse(readFileSync(indexesFile, 'utf8'));
const groups = JSON.parse(readFileSync(encodingsFile, 'utf8'));

/** What a source file holds as it is, and what it escapes: nothing a reader
 *  or an editor could take for something else. */
function quoted(code) {
  if (code === 0x27) return "\\'";
  if (code === 0x5c) return '\\\\';
  const plain =
    (code >= 0x20 && code < 0x7f) ||
    (code >= 0xa1 && code < 0x2000 && code !== 0xad) ||
    (code >= 0x2e80 && code < 0xd800) ||
    (code >= 0xf900 && code < 0xfe00) ||
    (code >= 0xff00 && code < 0xfff0) ||
    (code >= 0x20000 && code < 0x30000);
  if (plain) return String.fromCodePoint(code);
  if (code > 0xffff) return `\\u{${code.toString(16)}}`;
  return `\\u${code.toString(16).padStart(4, '0')}`;
}

function encoded(index) {
  let out = '';
  for (let i = 0; i < index.length;) {
    if (index[i] === null) {
      let run = 0;
      while (i < index.length && index[i] === null && run < 0xd000) {
        run += 1;
        i += 1;
      }
      out += `\\uffff${quoted(run)}`;
      continue;
    }
    if (index[i] === 0xffff) throw new Error('an index holds U+FFFF');
    out += quoted(index[i]);
    i += 1;
  }
  return out;
}

const constant = (name) => name.toUpperCase().replace(/[^A-Z0-9]/g, '_');
const MULTI = ['big5', 'euc-kr', 'gb18030', 'jis0208', 'jis0212'];
const single = Object.keys(indexes).filter(
  (name) =>
    !MULTI.includes(name) &&
    name !== 'gb18030-ranges' &&
    name !== 'iso-2022-jp-katakana',
);

const tables = [
  '// Generated by scripts/encoding-tables.mjs from the WHATWG Encoding',
  "// Standard's indexes.json. Do not edit. Nothing but strings, so a module",
  '// that imports it pays for a parse and for nothing until a table is read.',
  '',
  '/** Each single-byte index by its name, from byte 0x80. */',
  'export const SINGLE_BYTE: Record<string, string> = {',
  ...single.map((name) => `  '${name}': '${encoded(indexes[name])}',`),
  '};',
  '',
  ...MULTI.map(
    (name) => `export const ${constant(name)} = '${encoded(indexes[name])}';`,
  ),
  '',
  `export const ISO_2022_JP_KATAKANA = '${encoded(indexes['iso-2022-jp-katakana'])}';`,
  '',
  '/** Index gb18030 ranges, pointer then code point, a pair at a time. */',
  `export const GB18030_RANGES = [${indexes['gb18030-ranges'].flat().join(', ')}];`,
  '',
];
writeFileSync('src/html/encoding-tables.ts', tables.join('\n'));

const named = groups.flatMap((group) => group.encodings);
const labels = [
  '// Generated by scripts/encoding-tables.mjs from the WHATWG Encoding',
  "// Standard's encodings.json. Do not edit.",
  '',
  '/** Each encoding, by its name, and the labels that name it. */',
  'export const ENCODING_LABELS: Record<string, string> = {',
  ...named.map(({ name, labels: list }) => `  '${name}': '${list.join(' ')}',`),
  '};',
  '',
];
writeFileSync('src/html/encoding-labels.ts', labels.join('\n'));
